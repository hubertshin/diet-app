export function matchesExercise(name, query) { return matches(name, query, EXERCISE_SYNONYMS); }

// 검색 정렬: 즐겨찾기 → 최근 → DB. 음식 검색과 같은 규칙.
export function searchExercises(query, { exercises = EXERCISES, customs = [], favorites = new Set(), recent = new Set(), limit = 30 } = {}) {
  const all = [...customs, ...exercises];
  const hits = all.filter(e => matchesExercise(e.name, query));
  const rank = e => (favorites.has(e.id) ? 0 : recent.has(e.id) ? 1 : 2);
  hits.sort((a, b) => rank(a) - rank(b) || a.name.length - b.name.length);
  return hits.slice(0, limit);
}

export function findExercise(id, customs = []) {
  return customs.find(e => e.id === id) || EXERCISES.find(e => e.id === id) || null;
}

// 소모 kcal: 단위당 kcal × 수량, 체중 비례 (78kg 기준). weight 가 없으면 기준 그대로.
export function exerciseKcal({ kcal, amount, weight = null, refWeight = 78 }) {
  const base = kcal * amount;
  const scaled = typeof weight === 'number' ? base * (weight / refWeight) : base;
  return Math.max(0, Math.round(scaled));
}
